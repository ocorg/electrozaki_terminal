-- One colour list for all accessories (owner, 2026-11-04): the owner's 72 colours
-- (picked from the iPhone Gomme range) plus the plain ones the pochettes needed.
-- Names in French (the database language), English and Arabic for the website.
-- Owner and managers add colours from Site web -> Catalogue -> Couleurs.
CREATE TABLE couleurs (
  nom        TEXT PRIMARY KEY,
  nom_en     TEXT,
  nom_ar     TEXT,
  hex        TEXT NOT NULL CHECK (hex ~ '^#[0-9A-F]{6}$'),
  -- how the website draws a colour one flat dot can't show
  motif      TEXT CHECK (motif IN ('transparent', 'multicolore', 'ecossais')),
  ordre      INT  NOT NULL DEFAULT 0,
  actif      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by UUID
);

